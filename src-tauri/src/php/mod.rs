/// Extensions enabled on Windows builds (DLL in `ext/`).
pub const WINDOWS_EXTENSIONS: &[&str] = &[
    "mysqli",
    "pdo_mysql",
    "pdo_pgsql",
    "pgsql",
    "mbstring",
    "openssl",
    "curl",
    "fileinfo",
    "gd",
    "intl",
    "zip",
    "exif",
    "sodium",
    "sockets",
    "bz2",
];

/// Modules we require for WordPress / common PHP apps.
pub const REQUIRED_MODULES: &[&str] = &[
    "mysqli",
    "pdo_mysql",
    "curl",
    "mbstring",
    "openssl",
    "zip",
    "gd",
];

#[derive(Debug, Clone)]
pub struct PhpIniOptions {
    pub upload_max_filesize: String,
    pub post_max_size: String,
    pub memory_limit: String,
    pub max_execution_time: String,
    pub max_input_time: String,
    pub opcache_enable: bool,
    pub xdebug: bool,
    /// `auto_prepend_file` (DevStack dump helper).
    pub auto_prepend_file: Option<PathBuf>,
}

impl PhpIniOptions {
    /// Enable the DevStack `dump()` helper when it has been written to `{tools}`.
    pub fn with_dump_helper(mut self, paths: &Paths) -> Self {
        let helper = crate::services::dump::php_helper_path(paths);
        if helper.exists() {
            self.auto_prepend_file = Some(helper);
        }
        self
    }
}

impl Default for PhpIniOptions {
    fn default() -> Self {
        Self {
            upload_max_filesize: "0".into(),
            post_max_size: "0".into(),
            memory_limit: "-1".into(),
            max_execution_time: "0".into(),
            max_input_time: "-1".into(),
            opcache_enable: true,
            xdebug: false,
            auto_prepend_file: None,
        }
    }
}

fn windows_extension_dir(install_dir: &Path) -> PathBuf {
    let ext = install_dir.join("ext");
    if ext.is_dir() {
        ext
    } else {
        install_dir.join("ext")
    }
}

fn extension_lines(install_dir: &Path) -> String {
    if cfg!(windows) {
        let ext_dir = windows_extension_dir(install_dir);
        // Absolute path — relative "ext" fails when cwd is a site folder (WP-CLI).
        let ext_disp = ext_dir.display().to_string().replace('\\', "/");
        let mut lines = format!("extension_dir = \"{ext_disp}\"\n");
        for name in WINDOWS_EXTENSIONS {
            lines.push_str(&format!("extension={name}\n"));
        }
        // OPcache is a zend extension on Windows builds.
        let opcache = ["php_opcache.dll", "opcache.dll"]
            .iter()
            .map(|n| ext_dir.join(n))
            .find(|p| p.exists());
        if let Some(p) = opcache {
            let p = p.display().to_string().replace('\\', "/");
            lines.push_str(&format!("zend_extension=\"{p}\"\n"));
        } else {
            lines.push_str("zend_extension=opcache\n");
        }
        lines
    } else {
        // static-php-cli / system builds typically bake extensions in.
        "; Extensions are compiled into this PHP binary (static-php-cli / system).\n".into()
    }
}

/// Write a DevStack-managed php.ini suited to huge apps/databases.
pub fn write_dev_php_ini(install_dir: &Path, opts: &PhpIniOptions) -> Result<PathBuf> {
    let path = install_dir.join("php.ini");
    let xdebug_block = if opts.xdebug {
        if cfg!(windows) {
            let ext = windows_extension_dir(install_dir);
            let dll = ["php_xdebug.dll", "xdebug.dll"]
                .iter()
                .map(|n| ext.join(n))
                .find(|p| p.exists());
            if let Some(p) = dll {
                let p = p.display().to_string().replace('\\', "/");
                format!(
                    "\nzend_extension=\"{p}\"\nxdebug.mode=debug,develop\nxdebug.start_with_request=trigger\n"
                )
            } else {
                "\nzend_extension=xdebug\nxdebug.mode=debug,develop\nxdebug.start_with_request=trigger\n"
                    .into()
            }
        } else {
            r#"
zend_extension=xdebug
xdebug.mode=debug,develop
xdebug.start_with_request=trigger
"#
            .into()
        }
    } else {
        "\n; xdebug disabled by DevStack\n".into()
    };

    let extensions = extension_lines(install_dir);
    let prepend = match &opts.auto_prepend_file {
        Some(p) => format!(
            "auto_prepend_file = \"{}\"",
            p.display().to_string().replace('\\', "/")
        ),
        None => "; auto_prepend_file =".to_string(),
    };

    let contents = format!(
        r#"; Generated by DevStack — tuned for large local apps / DB imports.
; Do not edit by hand if you want DevStack to keep managing this file.

[PHP]
engine = On
short_open_tag = Off
precision = 14
output_buffering = 4096
zlib.output_compression = Off
implicit_flush = Off
serialize_precision = -1
zend.enable_gc = On
expose_php = Off
max_execution_time = {max_execution_time}
max_input_time = {max_input_time}
max_input_vars = 10000
memory_limit = {memory_limit}
error_reporting = E_ALL
display_errors = On
display_startup_errors = On
log_errors = On
error_log = php_errors.log
variables_order = "GPCS"
request_order = "GP"
register_argc_argv = Off
auto_globals_jit = On
post_max_size = {post_max_size}
upload_max_filesize = {upload_max_filesize}
max_file_uploads = 100
default_socket_timeout = 60
date.timezone = UTC
; Required for Apache/Nginx + php-cgi on Windows ("No input file specified").
cgi.fix_pathinfo = 1
{prepend}
; Never set doc_root / user_dir for local stacks — breaks SCRIPT_FILENAME.
; doc_root =
; user_dir =
; open_basedir =
{extensions}
[opcache]
opcache.enable = {opcache_enable}
opcache.enable_cli = {opcache_enable}
opcache.memory_consumption = 256
opcache.interned_strings_buffer = 16
opcache.max_accelerated_files = 20000
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
{xdebug_block}
"#,
        max_execution_time = opts.max_execution_time,
        max_input_time = opts.max_input_time,
        memory_limit = opts.memory_limit,
        post_max_size = opts.post_max_size,
        upload_max_filesize = opts.upload_max_filesize,
        opcache_enable = if opts.opcache_enable { "1" } else { "0" },
        extensions = extensions,
        xdebug_block = xdebug_block,
        prepend = prepend,
    );

    fs::write(&path, &contents)?;
    let alt = php_ini_path(install_dir);
    if alt != path {
        let _ = fs::write(alt, &contents);
    }
    Ok(path)
}

/// Point a [`Command`] at the DevStack-managed php.ini (`PHPRC` + `-c`).
pub fn apply_php_ini_to_command(cmd: &mut Command, install_dir: &Path) {
    let ini = php_ini_path(install_dir);
    if ini.exists() {
        if let Some(parent) = ini.parent() {
            cmd.env("PHPRC", parent);
        }
        cmd.arg("-c").arg(&ini);
    }
}

/// Regenerate managed php.ini for every installed PHP version.
pub fn regenerate_all_php_ini(paths: &Paths, state: &AppState) -> Result<usize> {
    let Some(installed) = state.installed.get("php") else {
        return Ok(0);
    };
    let mut n = 0;
    for rec in installed {
        let mut opts = PhpIniOptions::default().with_dump_helper(paths);
        if let Some(settings) = state.php_extensions.get(&rec.version) {
            opts.xdebug = settings.xdebug;
        }
        let dir = if rec.path.exists() {
            rec.path.clone()
        } else {
            paths.package_dir("php", &rec.version)
        };
        if dir.exists() {
            write_dev_php_ini(&dir, &opts)?;
            n += 1;
        }
    }
    Ok(n)
}

/// Run `php -m` and return loaded module names (lowercase).
pub fn list_loaded_modules(php_bin: &Path, install_dir: &Path) -> Result<Vec<String>> {
    let mut cmd = crate::services::process::command(php_bin);
    apply_php_ini_to_command(&mut cmd, install_dir);
    cmd.arg("-m");
    let out = cmd
        .output()
        .map_err(|e| DevStackError::Message(format!("php -m failed: {e}")))?;
    if !out.status.success() {
        return Err(DevStackError::Message(format!(
            "php -m error: {}",
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let modules: Vec<String> = text
        .lines()
        .map(|l| l.trim().to_ascii_lowercase())
        .filter(|l| !l.is_empty() && !l.starts_with('[') && *l != "zend modules")
        .collect();
    Ok(modules)
}

pub fn missing_required_modules(loaded: &[String]) -> Vec<String> {
    REQUIRED_MODULES
        .iter()
        .filter(|m| !loaded.iter().any(|l| l == **m))
        .map(|s| (*s).to_string())
        .collect()
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PhpExtensionView {
    pub version: String,
    pub xdebug: bool,
    pub ini_path: Option<PathBuf>,
    #[serde(default)]
    pub missing_modules: Vec<String>,
    #[serde(default)]
    pub loaded_modules: Vec<String>,
}

pub fn list_php_extensions(state: &AppState, paths: &Paths) -> Vec<PhpExtensionView> {
    let mut out = Vec::new();
    let Some(installed) = state.installed.get("php") else {
        return out;
    };
    for rec in installed {
        let settings = state
            .php_extensions
            .get(&rec.version)
            .cloned()
            .unwrap_or_default();
        let install = if rec.path.exists() {
            rec.path.clone()
        } else {
            paths.package_dir("php", &rec.version)
        };
        let php_bin = crate::services::process::find_bin(&install, &["php", "php.exe"])
            .unwrap_or_else(|| install.join(if cfg!(windows) { "php.exe" } else { "php" }));
        let (loaded, missing) = match list_loaded_modules(&php_bin, &install) {
            Ok(mods) => {
                let miss = missing_required_modules(&mods);
                (mods, miss)
            }
            Err(_) => (Vec::new(), REQUIRED_MODULES.iter().map(|s| (*s).to_string()).collect()),
        };
        out.push(PhpExtensionView {
            version: rec.version.clone(),
            xdebug: settings.xdebug,
            ini_path: Some(php_ini_path(&install)),
            missing_modules: missing,
            loaded_modules: loaded,
        });
    }
    out
}

pub fn set_xdebug(
    state: &mut AppState,
    paths: &Paths,
    version: &str,
    enabled: bool,
) -> Result<PhpExtensionView> {
    let install = state
        .installed
        .get("php")
        .and_then(|list| list.iter().find(|r| r.version == version))
        .ok_or_else(|| crate::error::DevStackError::VersionNotFound(version.into()))?
        .path
        .clone();

    let entry = state
        .php_extensions
        .entry(version.to_string())
        .or_insert_with(PhpExtensionSettings::default);
    entry.xdebug = enabled;

    let mut opts = PhpIniOptions::default().with_dump_helper(paths);
    opts.xdebug = enabled;
    let ini_path = write_dev_php_ini(&install, &opts)?;
    save_state(&paths.state_file, state)?;

    let php_bin = crate::services::process::find_bin(&install, &["php", "php.exe"])
        .unwrap_or_else(|| install.join(if cfg!(windows) { "php.exe" } else { "php" }));
    let (loaded, missing) = match list_loaded_modules(&php_bin, &install) {
        Ok(mods) => {
            let miss = missing_required_modules(&mods);
            (mods, miss)
        }
        Err(_) => (Vec::new(), Vec::new()),
    };

    Ok(PhpExtensionView {
        version: version.to_string(),
        xdebug: enabled,
        ini_path: Some(ini_path),
        missing_modules: missing,
        loaded_modules: loaded,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn windows_ini_contains_absolute_extension_dir_and_mysqli() {
        let dir = std::env::temp_dir().join(format!("devstack-phpini-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("ext")).unwrap();
        write_dev_php_ini(&dir, &PhpIniOptions::default()).unwrap();
        let raw = fs::read_to_string(dir.join("php.ini")).unwrap();
        assert!(
            raw.contains("cgi.fix_pathinfo = 1"),
            "cgi.fix_pathinfo required for php-cgi SCRIPT_FILENAME"
        );
        assert!(
            !raw.lines().any(|l| {
                let t = l.trim();
                !t.starts_with(';')
                    && (t.starts_with("doc_root") || t.starts_with("user_dir"))
                    && t.contains('=')
                    && !t.ends_with('=')
                    && !t.ends_with("= ")
            }),
            "doc_root/user_dir must stay unset:\n{raw}"
        );
        if cfg!(windows) {
            assert!(raw.contains("extension=mysqli"));
            assert!(raw.contains("extension=pdo_mysql"));
            assert!(raw.contains("extension=curl"));
            assert!(raw.contains("extension_dir = \""));
            assert!(!raw.contains("extension_dir = \"ext\""));
            assert!(raw.contains("zend_extension"));
        } else {
            assert!(raw.contains("compiled into this PHP binary") || raw.contains("static-php"));
        }
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_required_detects_mysqli() {
        let loaded = vec!["curl".into(), "mbstring".into(), "openssl".into()];
        let miss = missing_required_modules(&loaded);
        assert!(miss.contains(&"mysqli".to_string()));
        assert!(miss.contains(&"pdo_mysql".to_string()));
    }
}
